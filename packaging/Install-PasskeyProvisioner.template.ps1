#Requires -Version 5.1
<#
.SYNOPSIS
    Installs or removes Passkey Provisioner @@VERSION@@ (generated by build\Build-Installer.ps1). ASCII only.
.DESCRIPTION
    Self-contained installer for Intune / Robopack: the EXE and an optional settings.json are embedded as base64, so this one
    script is the whole package. Meant to run as SYSTEM. The application itself runs as a standard user and only writes to
    %LOCALAPPDATA%, so the install folder stays read-only for users.
    Exit codes: 0 done, 1618 the application is running (Intune retries later), 1 error.
.EXAMPLE
    powershell.exe -NoProfile -ExecutionPolicy Bypass -File Install-PasskeyProvisioner.ps1
.EXAMPLE
    powershell.exe -NoProfile -ExecutionPolicy Bypass -File Install-PasskeyProvisioner.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [string]$TargetDir = '@@TARGETDIR@@',
    [switch]$Uninstall,
    [string]$ShortcutDir = (Join-Path $env:ProgramData 'Microsoft\Windows\Start Menu\Programs'),
    [string]$LogPath = (Join-Path $env:SystemRoot 'Logs\Software\PasskeyProvisioner-install.log')
)

$ErrorActionPreference = 'Stop'
$version = '@@VERSION@@'
$exeName = 'PasskeyProvisioner.exe'
$shortcutName = 'Passkey Provisioner.lnk'
$exeBase64 = '@@EXE@@'
$settingsBase64 = '@@SETTINGS@@'   # empty when the package carries no settings.json
$logFile = $LogPath

function Write-InstallLog([string]$Text) {
    $line = '{0:yyyy-MM-dd HH:mm:ss} {1}' -f (Get-Date), $Text
    Write-Output $line
    try {
        [void][System.IO.Directory]::CreateDirectory((Split-Path -Parent $logFile))
        Add-Content -LiteralPath $logFile -Value $line -Encoding ASCII
    } catch { $null = $_ }
}

function Test-AppRunning {
    # A process whose path is unknown counts as running; replacing a running EXE fails anyway.
    $full = [System.IO.Path]::GetFullPath($TargetDir).TrimEnd('\') + '\'
    @(Get-Process -Name ([System.IO.Path]::GetFileNameWithoutExtension($exeName)) -ErrorAction SilentlyContinue |
            Where-Object { -not $_.Path -or $_.Path.StartsWith($full, [System.StringComparison]::OrdinalIgnoreCase) }).Count -gt 0
}

try {
    $action = if ($Uninstall) { 'Uninstall' } else { 'Install' }
    Write-InstallLog ('{0} Passkey Provisioner {1} in {2} as {3}' -f $action, $version, $TargetDir, [Environment]::UserName)
    if (Test-AppRunning) {
        Write-InstallLog 'Passkey Provisioner is running, exit 1618 (retry later)'
        exit 1618
    }

    $shortcut = Join-Path $ShortcutDir $shortcutName
    if (Test-Path -LiteralPath $TargetDir) { Remove-Item -LiteralPath $TargetDir -Recurse -Force }
    if (Test-Path -LiteralPath $shortcut) { Remove-Item -LiteralPath $shortcut -Force }

    if ($Uninstall) {
        # Remove the company folder too when it is now empty (never a Program Files root).
        $parent = Split-Path -Parent $TargetDir
        $roots = @($env:ProgramFiles, ${env:ProgramFiles(x86)}, $env:ProgramW6432) | Where-Object { $_ } | ForEach-Object { $_.TrimEnd('\') }
        if ($parent -and ($roots -notcontains $parent.TrimEnd('\')) -and (Test-Path -LiteralPath $parent) -and
            -not (Get-ChildItem -LiteralPath $parent -Force | Select-Object -First 1)) {
            Remove-Item -LiteralPath $parent -Force
        }
        Write-InstallLog 'Removed'
        exit 0
    }

    [void][System.IO.Directory]::CreateDirectory($TargetDir)
    $exePath = Join-Path $TargetDir $exeName
    [System.IO.File]::WriteAllBytes($exePath, [Convert]::FromBase64String($exeBase64))
    if ($settingsBase64) {
        [System.IO.File]::WriteAllBytes((Join-Path $TargetDir 'settings.json'), [Convert]::FromBase64String($settingsBase64))
    }

    [void][System.IO.Directory]::CreateDirectory($ShortcutDir)
    $shell = New-Object -ComObject WScript.Shell
    $link = $shell.CreateShortcut($shortcut)
    $link.TargetPath = $exePath
    $link.WorkingDirectory = $TargetDir
    $link.IconLocation = $exePath + ',0'
    $link.Description = 'Registers FIDO2 security keys in Microsoft Entra ID on behalf of users'
    $link.Save()

    $fileVersion = (Get-Item -LiteralPath $exePath).VersionInfo.FileVersion
    Write-InstallLog ('Installed {0} (file version {1})' -f $exePath, $fileVersion)
    exit 0
} catch {
    Write-InstallLog ('ERROR: ' + $_.Exception.Message)
    exit 1
}
